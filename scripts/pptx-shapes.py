#!/usr/bin/env python3
"""Turn the OOXML preset shape definitions (presetShapeDefinitions.xml from
ECMA-376, also shipped by Apache POI and LibreOffice) into web/js/pptx/shapes.js.

    curl -LO https://raw.githubusercontent.com/apache/poi/trunk/poi/src/main/resources/org/apache/poi/sl/draw/geom/presetShapeDefinitions.xml
    scripts/pptx-shapes.py presetShapeDefinitions.xml

Each shape becomes {av: {adj: default}, gd: ["name fmla", ...], rect: [l, t, r, b],
paths: [{w, h, fill, stroke, d: "M x y;L x y;A wR hR st sw;Q ..;C ..;Z"}]}.
"""
import json, os, sys
import xml.etree.ElementTree as ET

A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "web", "js", "pptx", "shapes.js")


def local(tag):
    return tag.split("}")[-1]


def pts(el):
    return [v for p in el.findall(A + "pt") for v in (p.get("x"), p.get("y"))]


def convert(src):
    shapes = {}
    for shape in ET.parse(src).getroot():
        out = {}
        av = shape.find(A + "avLst")
        if av is not None and len(av):
            out["av"] = {g.get("name"): int(g.get("fmla").split()[1]) for g in av}
        gd = shape.find(A + "gdLst")
        if gd is not None and len(gd):
            out["gd"] = [f'{g.get("name")} {" ".join(g.get("fmla").split())}' for g in gd]
        rect = shape.find(A + "rect")
        if rect is not None:
            out["rect"] = [rect.get(k) for k in ("l", "t", "r", "b")]
        paths = []
        for p in shape.find(A + "pathLst"):
            cmds = []
            for c in p:
                kind = local(c.tag)
                if kind == "moveTo":
                    cmds.append("M " + " ".join(pts(c)))
                elif kind == "lnTo":
                    cmds.append("L " + " ".join(pts(c)))
                elif kind == "arcTo":
                    cmds.append("A " + " ".join(c.get(k) for k in ("wR", "hR", "stAng", "swAng")))
                elif kind == "quadBezTo":
                    cmds.append("Q " + " ".join(pts(c)))
                elif kind == "cubicBezTo":
                    cmds.append("C " + " ".join(pts(c)))
                elif kind == "close":
                    cmds.append("Z")
                else:
                    raise ValueError(f"unknown path command {kind}")
            path = {"d": ";".join(cmds)}
            for k in ("w", "h"):
                if p.get(k):
                    path[k] = int(p.get(k))
            if p.get("fill") and p.get("fill") != "norm":
                path["fill"] = p.get("fill")
            if p.get("stroke") in ("false", "0"):
                path["stroke"] = False
            paths.append(path)
        out["paths"] = paths
        shapes[local(shape.tag)] = out
    return shapes


if __name__ == "__main__":
    shapes = convert(sys.argv[1])
    with open(OUT, "w") as f:
        f.write("// Preset shape geometry from ECMA-376 presetShapeDefinitions.xml,\n"
                "// generated by scripts/pptx-shapes.py. Don't edit by hand.\n")
        f.write("export default ")
        json.dump(shapes, f, separators=(",", ":"))
        f.write(";\n")
    print(f"{len(shapes)} shapes → {OUT} ({os.path.getsize(OUT) // 1024} KB)")
